/** Compile the research client into the host module-loader format. */
import {build} from 'esbuild'
import {writeFile} from 'node:fs/promises'
import {fileURLToPath} from 'node:url'
const root=fileURLToPath(new URL('../',import.meta.url))
const result=await build({absWorkingDir:root,entryPoints:['client/src/index.jsx'],bundle:true,write:false,minifyWhitespace:true,format:'cjs',platform:'browser',target:'es2022',external:['react'],loader:{'.css':'text'},legalComments:'none'})
await writeFile(new URL('../client/index.js',import.meta.url),'/** Generated by scripts/build-client.mjs; edit client/src. */\nwindow.__ModuleLoader__.load({id:"dsh-deep-insight",factory:require=>{const module={exports:{}};\n'+result.outputFiles[0].text+'\nreturn module.exports;}})\n')
